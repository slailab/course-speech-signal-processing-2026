"""Text processing (guide: docs/02_text_processing.md).

raw text -> text normalization -> words -> pronunciation lexicon.
G2P for OOV words and the alignment are done in step 3.

Reads the manifest written by step 1 and writes the MFA inputs (a .lab next to
each output audio file, e.g. audio/0001/example_0001.lab) and mfa/lexicon.txt,
and text_info.normalized_text into the manifest. Prints every normalization
sub-step and the dictionary lookup of each word (OOV words are marked; their
pronunciations are generated by G2P in step 3).
Usage: python src/process_text.py
"""

import re
from pathlib import Path

from tutorial_lib import (
    audio_root,
    english_cleaners_module,
    load_config,
    mfa_safe,
    output_manifest,
    read_lexicon,
    read_manifest,
    utt_id,
    write_manifest,
)


def main():
    cfg = load_config()
    p = cfg["paths"]
    cl = english_cleaners_module(cfg)
    lexicon = read_lexicon(cfg["text"]["lexicon"])  # {word: [pronunciation, ...]}
    # Optional extra pronunciations: a word listed there replaces its lexicon entries
    if cfg["text"].get("lexicon_extra"):
        extra = read_lexicon(cfg["text"]["lexicon_extra"])
        lexicon.update(extra)
        print(f"lexicon_extra: {len(extra)} words from {cfg['text']['lexicon_extra'].name}")
    # The manifest written by step 1: only utterances that passed step 1
    entries = read_manifest(output_manifest(cfg))
    root = audio_root(cfg)

    for entry in entries:
        # Raw text from the manifest
        uid, text = utt_id(entry, root), entry["text_info"]["text"]
        print(f"== {uid}")
        print(f"  raw                 : {text}")
        t = text

        # Text normalization: english_cleaners = these five sub-steps in this
        # order; print the result of each
        for step in (
            cl.convert_to_ascii,
            cl.lowercase,
            cl.expand_numbers,
            cl.expand_abbreviations,
            cl.collapse_whitespace,
        ):
            new = step(t)
            print(f"  {step.__name__:20s}: {new}{'' if new != t else '   (no change)'}")
            t = new

        # Word splitting: remove brackets and quotes that MFA would keep attached
        # to words, then write the .lab file next to the audio (MFA input)
        t = mfa_safe(t)
        (p["work"] / Path(entry["audio"]).with_suffix(".lab")).write_text(
            t + "\n", encoding="utf-8"
        )
        entry["text_info"]["normalized_text"] = t
        print(f"  -> .lab             : {t}")

        # Lexicon lookup; OOV words are handled by G2P in step 3
        print("  lexicon lookup:")
        for w in re.findall(r"[a-z']+", t):
            prons = lexicon.get(w)
            print(f"    {w:12s} {' | '.join(prons) if prons else 'OOV -> G2P in step 3'}")

    write_manifest(output_manifest(cfg), entries)
    # Copy of the lexicon in the MFA folder; step 3 adds the G2P pronunciations
    (p["work"] / "mfa").mkdir(exist_ok=True)
    with open(p["work"] / "mfa" / "lexicon.txt", "w", encoding="utf-8") as f:
        for word, prons in lexicon.items():
            f.writelines(f"{word}\t{pron}\n" for pron in prons)
    lexicon_path = p["work"] / "mfa" / "lexicon.txt"
    print(f"\nwrote .lab files, manifest.jsonl and {lexicon_path} ({len(lexicon)} words)")


if __name__ == "__main__":
    main()
